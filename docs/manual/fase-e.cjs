const L = require('./lib.cjs')
const F = __dirname + '/ficheros/'
;(async () => {
  const browser = await L.launch()
  const page = await L.open(browser, 'marta', { viewport: { width: 1280, height: 1000 } })
  await page.getByRole('button', { name: 'Importar' }).click()
  await page.waitForSelector('.ed-drop')
  await L.mark(page, [
    [page.getByRole('button', { name: /Plantilla Excel/ }).locator('..'), 1, { pos: 'l' }],
    ['.ed-drop', 2, { pos: 'l' }],
  ])
  await L.shot(page, 'importar-1', { x: 0, y: 120, width: 1280, height: 720 })
  await L.unmark(page)

  await page.setInputFiles('input[type=file]', F + 'leads_redes_octubre.csv')
  await page.waitForSelector('.ed-stat')
  await page.waitForTimeout(800)
  const stats = page.locator('.ed-grid--3').first()
  const sb = await stats.boundingBox()
  const opt = page.locator('.ed-panel.ed-grid--2')
  const ob = await opt.boundingBox()
  await L.shot(page, 'importar-resumen', { x: 0, y: sb.y - 110, width: 1280, height: ob.y + ob.height - sb.y + 130 })
  const resolver = page.locator('.ed-panel', { hasText: '¿A qué estudio se refieren?' })
  console.log('sin reconocer:', await resolver.locator('tbody tr td:first-child').allInnerTexts())
  // «Fotografía digital» no es nuestro; el resto se deja elegir
  const rows = resolver.locator('tbody tr')
  const n = await rows.count()
  for (let i = 0; i < n; i++) {
    const t = await rows.nth(i).locator('td').first().innerText()
    if (/fotograf/i.test(t)) await rows.nth(i).locator('select').selectOption('0')
    if (/interior/i.test(t)) await rows.nth(i).locator('select').selectOption('0')
  }
  await page.waitForTimeout(500)
  await L.shot(page, 'importar-estudios', resolver, 10)
  await page.locator('details.ed-panel summary').click()
  await page.waitForTimeout(400)
  await L.shot(page, 'importar-columnas', page.locator('details.ed-panel'), 10)
  await page.locator('details.ed-panel summary').click()
  const sample = page.locator('h3', { hasText: 'Así se guardarán' }).locator('..')
  await L.shot(page, 'importar-muestra', sample, 10)
  const btn = page.getByRole('button', { name: /^Importar \d/ })
  await L.mark(page, [[btn, 1, { pos: 'tr' }]])
  await L.shot(page, 'importar-boton', btn.locator('..'), { x: 10, y: 16, b: 10 })
  await L.unmark(page)
  console.log('botón:', await btn.innerText())
  await btn.click()
  await page.waitForSelector('text=Importar otro fichero')
  await page.waitForTimeout(800)
  await page.addStyleTag({ content: '.ed-toasts{display:none!important}' })
  await L.shot(page, 'importar-resultado', { x: 0, y: 120, width: 1280, height: 560 })

  // Contactos antiguos al histórico
  await page.getByRole('button', { name: /Importar otro fichero/ }).click()
  await page.setInputFiles('input[type=file]', F + 'contactos_antiguos_sac.csv')
  await page.waitForSelector('.ed-stat')
  await page.waitForTimeout(800)
  await page.locator('.ed-panel.ed-grid--2 select').first().selectOption('ANO_PASADO')
  await page.waitForTimeout(1200)
  await page.locator('.ed-check', { hasText: 'Contactos antiguos' }).click()
  await page.waitForTimeout(300)
  const opt2 = page.locator('.ed-panel.ed-grid--2')
  await L.mark(page, [[opt2.locator('.ed-check'), 1, { pos: 'l' }]])
  await L.shot(page, 'importar-historico', opt2, 16)
  await L.unmark(page)
  const btn2 = page.getByRole('button', { name: /^Importar \d/ })
  console.log('botón 2:', await btn2.innerText())
  await L.shot(page, 'importar-historico-boton', btn2.locator('..'), 10)
  await btn2.click()
  await page.waitForSelector('text=Importar otro fichero')
  await page.waitForTimeout(800)
  await L.shot(page, 'importar-historico-resultado', { x: 0, y: 260, width: 1280, height: 300 })
  const hist = page.locator('h3', { hasText: 'Últimas importaciones' }).locator('..')
  await L.shot(page, 'importar-ultimas', hist, 10)

  await page.getByRole('button', { name: /Ir a los leads/ }).click()
  await page.waitForSelector('.ed-lead')
  await L.goTab(page, 'historico')
  await L.shot(page, 'historico', { x: 0, y: 120, width: 1280, height: 520 })
  await page.fill('.ed-search input', 'rocío')
  await page.waitForTimeout(1200)
  await L.shot(page, 'fila-historico', L.row(page, 'Rocío Fuentes Lara'), 6)
  await browser.close()
})().catch((e) => { console.error(e); process.exit(1) })
